#!/usr/bin/env python3
"""Builds supabase/seed/02_communes.sql from scripts/data/communes_dz.txt.

    python3 scripts/build-communes-sql.py

The source lists the communes of the 2019 wilayas (49-58) twice: under the new wilaya and under
the wilaya they were split from. Each commune is kept once, under the new wilaya. The generated SQL
only inserts communes that are missing, so it is safe to run on a live database.
"""
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts/data/communes_dz.txt"
TARGET = ROOT / "supabase/seed/02_communes.sql"

# 2019 wilayas and the wilaya each one was split from.
SPLIT_FROM = {49: 1, 50: 1, 51: 7, 52: 8, 53: 11, 54: 11, 55: 30, 56: 33, 57: 39, 58: 47}
# Same commune, different spelling in the source (new-wilaya spelling -> former-wilaya spelling).
ALIASES = {
    "tenedla": "tendla", "temacine": "tamacine", "blidet amor": "balidat ameur", "el alia": "el allia",
    "tabelbala": "tabalbala", "foggaret azzaouia": "foggaret ezzaouia", "chaiba": "ech chaiba",
    "ras el miad": "ras el miaad", "bordj badji mokhtar": "b badji mokhtar", "sidi khelil": "sidi khellil",
}


def key(name: str) -> str:
    s = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", " ", s).strip()


def main() -> None:
    lists: dict[int, list[str]] = {}
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        code, *names = line.split("|")
        seen, unique = set(), []
        for n in (x.strip() for x in names):
            if n and key(n) not in seen:
                seen.add(key(n))
                unique.append(n)
        lists[int(code)] = unique

    errors = []
    for new, parent in SPLIT_FROM.items():
        for name in lists.get(new, []):
            k = ALIASES.get(key(name), key(name))
            before = len(lists[parent])
            lists[parent] = [n for n in lists[parent] if key(n) != k]
            if len(lists[parent]) == before:
                errors.append(f"{new:02d} {name}: not found under {parent:02d}")
    if errors:
        sys.exit("Unmatched communes:\n  " + "\n  ".join(errors))

    def sql(s: str) -> str:
        return s.replace("'", "''")

    rows = [(code, name) for code in sorted(lists) for name in lists[code]]
    with TARGET.open("w", encoding="utf-8") as f:
        f.write("-- Communes of wilayas 01-58 (French names). Generated by scripts/build-communes-sql.py from\n")
        f.write("-- scripts/data/communes_dz.txt; do not edit by hand. Only missing communes are inserted.\n")
        f.write("-- Communes of the 2019 wilayas (49-58) are listed under the new wilaya only.\n")
        f.write("insert into communes (wilaya_code, name)\nselect v.code, jsonb_build_object('fr', v.name, 'en', v.name)\n  from (values\n")
        f.write(",\n".join(f"    ({c}, '{sql(n)}')" for c, n in rows))
        f.write("\n  ) as v(code, name)\n")
        f.write(" where exists (select 1 from wilayas w where w.code = v.code)\n")
        f.write("   and not exists (select 1 from communes c where c.wilaya_code = v.code and c.name->>'fr' = v.name);\n")
    counts = {c: len(v) for c, v in lists.items()}
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(rows)} communes in {len(counts)} wilayas")
    print("per wilaya:", " ".join(f"{c:02d}:{n}" for c, n in sorted(counts.items())))


if __name__ == "__main__":
    main()
