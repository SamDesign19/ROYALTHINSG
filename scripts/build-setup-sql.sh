#!/usr/bin/env bash
# Builds supabase/setup.sql = all migrations + reference seed, for pasting into the
# Supabase SQL Editor when the Supabase CLI is not available.
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- ROYAL INK — full database setup (generated by scripts/build-setup-sql.sh; do not edit)."
  echo "-- Run once on an EMPTY Supabase project: SQL Editor -> New query -> paste -> Run."
  echo "begin;"
  for f in supabase/migrations/*.sql supabase/seed/*.sql; do
    echo; echo "-- ===== $f ====="; cat "$f"
  done
  echo; echo "commit;"
} > supabase/setup.sql
echo "wrote supabase/setup.sql ($(wc -l < supabase/setup.sql) lines)"
